"""Backend contracts. receive() must return owned bytes and respect its timeout (seconds)."""

from __future__ import annotations

from typing import Any, Protocol

from .types import CameraCapabilities, CameraConfiguration, CameraInfo, Frame


class CameraDevice(Protocol):
    info: CameraInfo
    configuration: CameraConfiguration

    def capabilities(self) -> CameraCapabilities: ...
    def configure(self, config: CameraConfiguration) -> CameraConfiguration: ...
    def read_feature(self, name: str) -> Any: ...
    def start(self) -> None: ...
    def receive(self, timeout: float) -> Frame | None: ...
    def software_trigger(self) -> None: ...
    def stop(self) -> None: ...
    def close(self) -> None: ...
    def statistics(self) -> dict[str, int | None]: ...


class CameraBackend(Protocol):
    name: str

    def discover(self) -> list[CameraInfo]: ...
    def open(self, camera_id: str) -> CameraDevice: ...
